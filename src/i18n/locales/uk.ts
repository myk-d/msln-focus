// Same nested key shape as `uk`, but with every leaf widened to `string` —
// `en.ts` needs to match uk's structure exactly without being forced to
// reuse its literal Ukrainian text as the value type.
type DeepStringRecord<T> = { [K in keyof T]: T[K] extends string ? string : DeepStringRecord<T[K]> };
export type Translations = DeepStringRecord<typeof uk>;
export default uk;
